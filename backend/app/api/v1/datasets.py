"""Dataset upload, profiling, and interactive analytical query endpoints.

Supports:
  - /upload           → standard single-request upload (up to FastAPI body limit)
  - /upload-chunk     → chunked multipart upload (one 10 MB slice at a time)
  - /upload-finalize  → assemble chunks + trigger profiling (call after all chunks sent)
"""

from __future__ import annotations

import shutil
import uuid
from pathlib import Path

from fastapi import APIRouter, BackgroundTasks, Depends, File, Form, HTTPException, Query, UploadFile
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import get_current_active_tenant_user, get_db

# Temp directory for in-flight chunked uploads (inside the container's /tmp)
_CHUNK_TMP = Path("/tmp/di_chunks")
_CHUNK_TMP.mkdir(parents=True, exist_ok=True)
from app.models.user import User
from app.schemas.dataset import (
    DatasetCorrelationsResponse,
    DatasetPreviewResponse,
    DatasetProfileResponse,
    DatasetQueryRequest,
    DatasetQueryResponse,
    DatasetResponse,
    DatasetUploadResponse,
    StructuredQueryRequest,
)
from app.services.dataset import DatasetService

router = APIRouter(prefix="/datasets", tags=["Datasets"])


@router.post(
    "/upload",
    response_model=DatasetUploadResponse,
    status_code=202,
    summary="Upload a dataset file (CSV / XLSX / JSON / Parquet / TSV)",
)
async def upload_dataset(
    workspace_id: uuid.UUID = Form(...),
    file: UploadFile = File(...),
    name: str | None = Form(None),
    description: str | None = Form(None),
    background_tasks: BackgroundTasks = None,
    current_user: User = Depends(get_current_active_tenant_user),
    db: AsyncSession = Depends(get_db),
):
    """Upload dataset and trigger async Polars/DuckDB profiling."""
    file_bytes = await file.read()
    svc = DatasetService(db)
    dataset = await svc.upload_dataset(
        workspace_id=workspace_id,
        filename=file.filename or "upload",
        file_bytes=file_bytes,
        actor=current_user,
        name=name,
        description=description,
        background_tasks=background_tasks,
    )
    return dataset


# ── Chunked Upload — Step 1: receive one slice ────────────────────────────────
@router.post(
    "/upload-chunk",
    status_code=200,
    summary="Upload a single chunk of a large file (10 MB per call)",
)
async def upload_chunk(
    upload_id: str = Form(...),       # UUID generated by the client for this upload session
    chunk_index: int = Form(...),     # 0-based chunk number
    total_chunks: int = Form(...),    # total number of chunks
    chunk: UploadFile = File(...),    # the raw binary chunk
    current_user: User = Depends(get_current_active_tenant_user),
):
    """Receives and stores one chunk. Call /upload-finalize when all chunks are sent."""
    # Validate upload_id is a safe UUID-like string
    try:
        uuid.UUID(upload_id)
    except ValueError:
        raise HTTPException(status_code=400, detail="upload_id must be a valid UUID.")

    chunk_dir = _CHUNK_TMP / upload_id
    chunk_dir.mkdir(parents=True, exist_ok=True)

    chunk_bytes = await chunk.read()
    chunk_path = chunk_dir / f"chunk_{chunk_index:06d}.bin"
    chunk_path.write_bytes(chunk_bytes)

    return {
        "status": "ok",
        "upload_id": upload_id,
        "chunk_index": chunk_index,
        "received_bytes": len(chunk_bytes),
        "total_chunks": total_chunks,
    }


# ── Chunked Upload — Step 2: assemble + profile ───────────────────────────────
@router.post(
    "/upload-finalize",
    status_code=202,
    summary="Assemble all uploaded chunks, profile dataset, and save to storage",
)
async def upload_finalize(
    upload_id: str = Form(...),
    total_chunks: int = Form(...),
    filename: str = Form(...),
    workspace_id: uuid.UUID = Form(...),
    name: str | None = Form(None),
    description: str | None = Form(None),
    background_tasks: BackgroundTasks = None,
    current_user: User = Depends(get_current_active_tenant_user),
    db: AsyncSession = Depends(get_db),
):
    """Assembles chunks, calls the normal upload pipeline, cleans up temp files."""
    try:
        uuid.UUID(upload_id)
    except ValueError:
        raise HTTPException(status_code=400, detail="upload_id must be a valid UUID.")

    chunk_dir = _CHUNK_TMP / upload_id
    if not chunk_dir.exists():
        raise HTTPException(status_code=404, detail=f"No chunks found for upload_id={upload_id}. Did you call /upload-chunk first?")

    # Assemble chunks in order
    assembled = bytearray()
    for i in range(total_chunks):
        chunk_path = chunk_dir / f"chunk_{i:06d}.bin"
        if not chunk_path.exists():
            raise HTTPException(
                status_code=400,
                detail=f"Missing chunk {i}/{total_chunks}. Upload incomplete — please retry.",
            )
        assembled.extend(chunk_path.read_bytes())

    # Clean up temp chunks
    try:
        shutil.rmtree(chunk_dir)
    except Exception:
        pass  # Non-critical, /tmp is ephemeral anyway

    # Delegate to the normal upload pipeline (handles storage + profiling)
    svc = DatasetService(db)
    dataset = await svc.upload_dataset(
        workspace_id=workspace_id,
        filename=filename,
        file_bytes=bytes(assembled),
        actor=current_user,
        name=name,
        description=description,
        background_tasks=background_tasks,
    )
    return dataset


